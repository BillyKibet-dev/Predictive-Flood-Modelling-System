"""Opt-in actual pg_dump/pg_restore of a disposable schema plus matching CAS files."""
import os
from pathlib import Path
import re
import shutil
import subprocess

import pytest
from sqlalchemy import text

from src.api.services.operational_snapshot_service import OperationalSnapshotService
from src.api.services.operational_source_storage import LocalEvidenceStore
from tests.test_operational_persistence import native,evidence


def test_real_paired_postgres_and_source_restore(native,evidence,tmp_path):
    engine,schema=native
    store,paths=evidence
    if not re.fullmatch(r'test_operational_[0-9a-f]{32}',schema):
        raise ValueError('Backup restore is restricted to the disposable fixture schema')
    dump=shutil.which('pg_dump')
    if not dump:
        candidates=sorted((Path(os.environ.get('PROGRAMFILES','C:/Program Files'))/'PostgreSQL').glob('*/bin/pg_dump.exe'))
        dump=str(candidates[-1]) if candidates else None
    if not dump:pytest.skip('PostgreSQL backup client binaries not installed')
    restore=str(Path(dump).with_name('pg_restore.exe' if os.name=='nt' else 'pg_restore'))
    result=OperationalSnapshotService(engine,store,schema=schema).persist(paths['available_12utc'])
    sid=result['snapshot_id']
    assert sid is not None
    archive=tmp_path/'isolated-schema.dump'
    url=engine.url.set(drivername='postgresql',password=None).render_as_string(hide_password=False)
    env=os.environ.copy()
    if engine.url.password is not None:env['PGPASSWORD']=engine.url.password
    dumped=subprocess.run([dump,'--dbname',url,'--schema',schema,'--format=custom','--file',str(archive)],
                          env=env,capture_output=True,timeout=60)
    assert dumped.returncode==0,'Isolated pg_dump failed; credentials and connection output withheld'
    copied=tmp_path/'restored_sources'
    shutil.copytree(store.root,copied)
    # The schema was generated by native() in this test; public is never dropped.
    with engine.begin() as conn:conn.execute(text(f'DROP SCHEMA "{schema}" CASCADE'))
    try:
        restored=subprocess.run([restore,'--dbname',url,'--exit-on-error','--no-owner','--no-privileges',str(archive)],
                                env=env,capture_output=True,timeout=60)
        assert restored.returncode==0,'Isolated pg_restore failed; connection output withheld'
        checked=OperationalSnapshotService(engine,LocalEvidenceStore(copied),schema=schema).check_snapshot(sid)
        assert checked['evidence_verified'] is True
        missing=OperationalSnapshotService(engine,LocalEvidenceStore(tmp_path/'missing_sources'),schema=schema).check_snapshot(sid)
        assert missing['evidence_verified'] is False
    finally:
        # Keep native() cleanup valid even if a restore client failed early.
        with engine.begin() as conn:conn.execute(text(f'CREATE SCHEMA IF NOT EXISTS "{schema}"'))
